const { chromium } = require('playwright');
const OUT = __dirname + '/v6/';
require('fs').mkdirSync(OUT, { recursive: true });
(async () => {
  const browser = await chromium.launch({ args: ['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist'] });
  const ctx = await browser.newContext({ viewport: { width: 430, height: 932 }, deviceScaleFactor: 1, isMobile: true, hasTouch: true });
  const page = await ctx.newPage(); const errs = [];
  page.on('pageerror', e => errs.push('PAGEERROR ' + e.message)); page.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
  await page.goto('http://localhost:5173/?local'); await page.fill('#i-seed', '478'); await page.click('#i-new'); await page.waitForTimeout(4000);
  const ev = (f, a) => page.evaluate(f, a);
  const shot = async (n, w = 1500) => { await page.waitForTimeout(w); await page.screenshot({ path: OUT + n + '.png', timeout: 120000 }); console.log('shot', n); };
  await ev(() => { const g = window.game; g.sim.paused = false; g.sim.speed = 10; });
  await page.waitForTimeout(9000);
  await ev(() => { const g = window.game; g.sim.speed = 1; g.sim.paused = true; const c = g.sim.cities[0]; g.renderer.focusOn(c.x + .5, c.y + .5, 11, true); });
  await page.waitForTimeout(2000);
  const pt = await ev(() => { const g = window.game, r = g.renderer; const c = g.sim.citizens.filter(c => !c.dead && c.age > 17).sort((a,b)=>(b.mind?.mem.length||0)-(a.mind?.mem.length||0))[0]; const p = r.screenOf(c.x, c.y - 0.0); const N = g.sim.world.size; const v = new r.camera.position.constructor(c.x - N / 2, g.sim.world.heightAt(c.x, c.y) + 0.25, c.y - N / 2).project(r.camera); const rect = r.three.domElement.getBoundingClientRect(); return { x: (v.x * .5 + .5) * rect.width, y: (-v.y * .5 + .5) * rect.height, name: c.name }; });
  await page.touchscreen.tap(pt.x, pt.y); await shot('1_card', 700);
  console.log(await ev(() => document.getElementById('c-title').textContent + ' | ' + document.getElementById('c-sub').innerText));
  await page.click('#c-actions button:nth-child(2)'); await shot('2_influence', 500);
  await page.click('#c-actions button:nth-child(1)'); await shot('3_dream_menu', 500);
  await page.locator('#msgs button').first().click(); await shot('4_after_dream', 700);
  console.log('snack:', await ev(() => document.getElementById('snack').innerText));
  await ev(() => document.querySelector('#card .cx').click());
  await page.waitForTimeout(300);
  await page.click('#c-actions button:nth-child(3)').catch(()=>{}); await shot('5_details', 900);
  console.log(await ev(() => document.getElementById('sheet-body').innerText.slice(0, 700)));
  console.log('erreurs', errs.slice(0, 5));
  await browser.close();
})();
